function renderLibPickers() {
  PICKER_PREFIXES.forEach(prefix => {
    const box = $(prefix + '-lib-picker');
    if (!box) return;
    const selSet = pickerSelSet(prefix);
    if (!libraries.length) {
      box.innerHTML = '<div class="muted small">暂无词库，请先在「词库」中创建</div>';
      updatePoolInfo(prefix);
      return;
    }
    box.innerHTML = libraries.map(lib => {
      const on = selSet.has(lib.id);
      const keyCount = lib.words.filter(w => w.isKey).length;
      const tags = [];
      if (lib.grade) tags.push(`<span class="lib-pick-tag blue">${esc(lib.grade)}</span>`);
      if (lib.unit) tags.push(`<span class="lib-pick-tag">${esc(lib.unit)}</span>`);
      if (lib.isKey) tags.push(`<span class="lib-pick-tag gold">重点库</span>`);
      if (keyCount) tags.push(`<span class="lib-pick-tag gray">重点 ${keyCount}</span>`);
      return `<label class="lib-pick${on ? ' on' : ''}" data-lib-pick="${prefix}" data-id="${lib.id}">
        <input type="checkbox"${on ? ' checked' : ''}>
        <span class="lib-pick-body">
          <span class="lib-pick-name">${esc(lib.name)}${tags.join('')}</span>
          <span class="lib-pick-meta">${lib.words.length} 个单词</span>
        </span>
      </label>`;
    }).join('');
    updatePoolInfo(prefix);
  });
}

function getPool(prefix) {
  const selSet = pickerSelSet(prefix);
  const keyOnly = pickerKeyOnly(prefix);
  const pool = [];
  libraries.forEach(lib => {
    if (!selSet.has(lib.id)) return;
    lib.words.forEach(w => {
      if (keyOnly && !w.isKey && !lib.isKey) return;
      pool.push({ word: w, lib });
    });
  });
  return pool;
}

function updatePoolInfo(prefix) {
  const selSet = pickerSelSet(prefix);
  const el = $(prefix + '-pool-info');
  if (!el) return;
  const selLibs = libraries.filter(l => selSet.has(l.id));
  const totalWords = selLibs.reduce((s, l) => s + l.words.length, 0);
  const pool = getPool(prefix);
  const keyOnly = pickerKeyOnly(prefix);
  el.textContent = `已选 ${selLibs.length} 个词库 · 共 ${totalWords} 词${keyOnly ? ` · 筛选后 ${pool.length} 词` : ''}`;
}

