function addWord(word, meaning, phonetic = '', example = '', isKey = false, silent = false) {
  word = String(word || '').trim();
  meaning = String(meaning || '').trim();
  if (!word)     { if (!silent) toast('请输入英文单词', 'err'); return false; }
  if (!meaning)  { if (!silent) toast('请输入中文释义', 'err'); return false; }
  if (words.some(w => w.word.toLowerCase() === word.toLowerCase())) {
    if (!silent) toast(`「${word}」在当前词库中已存在`, 'err'); return false;
  }
  words.push({ id: uid(), word, meaning, phonetic: String(phonetic).trim(), example: String(example).trim(), isKey: !!isKey });
  return true;
}

