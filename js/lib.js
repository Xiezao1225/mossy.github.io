function importWordsToLib(rawList, targetLib) {
  if (!Array.isArray(rawList)) return { added: 0, skipped: 0 };
  let added = 0, skipped = 0;
  rawList.forEach(item => {
    if (!item || typeof item !== 'object') { skipped++; return; }
    const word = String(item.word ?? item.en ?? item.english ?? '').trim();
    const meaning = String(item.meaning ?? item.cn ?? item.chinese ?? item.translation ?? item.zh ?? '').trim();
    if (!word || !meaning) { skipped++; return; }
    if (targetLib.words.some(w => w.word.toLowerCase() === word.toLowerCase())) { skipped++; return; }
    targetLib.words.push({
      id: uid(), word, meaning,
      phonetic: String(item.phonetic ?? item.phonetics ?? item.us ?? item.uk ?? '').trim(),
      example: String(item.example ?? item.sentence ?? '').trim(),
      isKey: toBool(item.isKey ?? item.key ?? item.keyword ?? false)
    });
    added++;
  });
  return { added, skipped };
}

function detectImportFormat(data) {
  if (data && typeof data === 'object' && !Array.isArray(data) && Array.isArray(data.libraries)) {
    return { mode: 'multi', libraries: data.libraries };
  }
  if (Array.isArray(data)) {
    if (data.length && data.every(item =>
      item && typeof item === 'object' && !Array.isArray(item) && Array.isArray(item.words)
    )) {
      return { mode: 'multi', libraries: data };
    }
    return { mode: 'words', words: data };
  }
  if (data && typeof data === 'object') {
    if (Array.isArray(data.words)) return { mode: 'named', lib: data };
    return { mode: 'words', words: [data] };
  }
  return { mode: 'invalid' };
}

function importFromText(text, silent = false) {
  let data;
  try { data = JSON.parse(text); }
  catch (e) { if (!silent) toast('JSON 解析失败：' + e.message, 'err'); return { added: 0, skipped: 0 }; }

  const fmt = detectImportFormat(data);
  if (fmt.mode === 'invalid') { if (!silent) toast('JSON 格式不支持', 'err'); return { added: 0, skipped: 0 }; }

  if (fmt.mode === 'words') {
    const lib = activeLib();
    if (!lib) { if (!silent) toast('没有可用词库', 'err'); return { added: 0, skipped: 0 }; }
    const res = importWordsToLib(fmt.words, lib);
    saveLibraries(); renderWords();
    if (!silent) toast(`导入到「${lib.name}」：新增 ${res.added} 个${res.skipped ? `，跳过 ${res.skipped} 个` : ''}`, res.added ? 'ok' : 'err');
    return res;
  }
  if (fmt.mode === 'named') {
    const raw = fmt.lib;
    const name = String(raw.name || '导入词库').trim() || '导入词库';
    let target = libraries.find(l => l.name === name);
    let isNew = false;
    if (!target) {
      target = normalizeLibrary({ name, grade: raw.grade, unit: raw.unit, isKey: raw.isKey, words: [] });
      libraries.push(target);
      isNew = true;
    } else {
      if (raw.grade && !target.grade) target.grade = String(raw.grade).trim();
      if (raw.unit && !target.unit) target.unit = String(raw.unit).trim();
      if (toBool(raw.isKey)) target.isKey = true;
    }
    const res = importWordsToLib(raw.words, target);
    if (isNew) activeLibId = target.id;
    saveLibraries(); renderWords();
    if (!silent) toast(`${isNew ? '新建' : '合并到'}词库「${name}」：新增 ${res.added} 个${res.skipped ? `，跳过 ${res.skipped} 个` : ''}`, res.added ? 'ok' : 'err');
    return res;
  }
  if (fmt.mode === 'multi') {
    const list = fmt.libraries || [];
    if (!list.length) { if (!silent) toast('多词库列表为空', 'err'); return { added: 0, skipped: 0 }; }
    let created = 0, merged = 0, totalAdded = 0, totalSkipped = 0;
    let firstNewId = null;
    const newNames = [];
    list.forEach(libData => {
      if (!libData || typeof libData !== 'object') return;
      const rawName = String(libData.name || '').trim();
      const name = rawName || `导入词库 ${libraries.length + 1}`;
      const rawWords = Array.isArray(libData.words) ? libData.words : [];
      let target = libraries.find(l => l.name === name);
      let isNew = false;
      if (!target) {
        target = normalizeLibrary({ name, grade: libData.grade, unit: libData.unit, isKey: libData.isKey, words: [] });
        libraries.push(target);
        isNew = true;
        if (!firstNewId) firstNewId = target.id;
        newNames.push(name);
      } else {
        if (libData.grade && !target.grade) target.grade = String(libData.grade).trim();
        if (libData.unit && !target.unit) target.unit = String(libData.unit).trim();
        if (toBool(libData.isKey)) target.isKey = true;
      }
      const res = importWordsToLib(rawWords, target);
      if (isNew) created++; else merged++;
      totalAdded += res.added;
      totalSkipped += res.skipped;
    });
    if (firstNewId) activeLibId = firstNewId;
    saveLibraries(); renderWords();
    if (!silent) {
      const parts = [];
      if (created) parts.push(`新建 ${created} 个`);
      if (merged) parts.push(`合并 ${merged} 个`);
      const detail = newNames.length ? `（新建：${newNames.join('、')}）` : '';
      toast(`导入 ${list.length} 个词库：${parts.join('，')}，共新增 ${totalAdded} 词${detail}`, totalAdded ? 'ok' : 'err');
    }
    return { added: totalAdded, skipped: totalSkipped };
  }
}

