function ensureIds(list){ list.forEach(w => { if (!w.id) w.id = uid(); }); return list; }

function normalizeLibrary(raw) {
  if (!raw || typeof raw !== 'object') return null;
  return {
    id: raw.id || uid(),
    name: String(raw.name || '未命名词库').trim() || '未命名词库',
    grade: String(raw.grade || '').trim(),
    unit: String(raw.unit || '').trim(),
    isKey: toBool(raw.isKey),
    words: ensureIds(Array.isArray(raw.words) ? raw.words.map(w => ({
      id: w.id || uid(),
      word: String(w.word || '').trim(),
      meaning: String(w.meaning || '').trim(),
      phonetic: String(w.phonetic || '').trim(),
      example: String(w.example || '').trim(),
      isKey: toBool(w.isKey)
    })).filter(w => w.word && w.meaning) : [])
  };
}

function loadLibraries() {
  for (const key of [LIBS_KEY, LEGACY_V3_KEY, LEGACY_V2_KEY]) {
    try {
      const raw = localStorage.getItem(key);
      if (raw) {
        const d = JSON.parse(raw);
        if (d && Array.isArray(d.libraries) && d.libraries.length) {
          libraries = d.libraries.map(normalizeLibrary).filter(Boolean);
          activeLibId = libraries.some(l => l.id === d.activeLibId) ? d.activeLibId : libraries[0].id;
          if (key !== LIBS_KEY) saveLibraries();
          return;
        }
      }
    } catch (e) {}
  }
  try {
    const old = localStorage.getItem(LEGACY_WORDS_KEY);
    if (old) {
      const arr = JSON.parse(old);
      if (Array.isArray(arr) && arr.length) {
        libraries = [normalizeLibrary({ name: '默认词库', words: arr })];
        activeLibId = libraries[0].id;
        saveLibraries();
        try { localStorage.removeItem(LEGACY_WORDS_KEY); } catch (e) {}
        return;
      }
    }
  } catch (e) {}
  libraries = BUILTIN_J9.map(normalizeLibrary);
  activeLibId = libraries[0].id;
  saveLibraries();
}

function saveLibraries() {
  try { localStorage.setItem(LIBS_KEY, JSON.stringify({ libraries, activeLibId })); }
  catch (e) { toast('保存失败：存储空间不足', 'err'); }
}

